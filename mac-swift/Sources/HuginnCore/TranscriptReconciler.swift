import Foundation

public struct DeEchoResult {
    public let text: String
    public let removedEchoes: Int
    public let meLines: Int
    public let themLines: Int
}

/// De-echoes a 2-track transcript ("Me" = microphone, "Them" = system audio).
/// When the user is on SPEAKERS the mic re-captures the remote party, so most
/// "Them" lines reappear a beat later as near-identical "Me" lines — their
/// words wrongly attributed to the user, and every utterance doubled.
///
/// Rests on a hard invariant: the "Them" track is the system's render side and
/// physically cannot contain the local microphone. On macOS that holds because
/// ScreenCaptureKit captures render-side audio with excludesCurrentProcessAudio
/// set, while the mic is a separate AVAudioEngine input. So a "Them" line is
/// always genuinely the remote party, and a "Me" line closely matching a
/// near-simultaneous "Them" line is that line bleeding back through the
/// speakers. Deterministic, text-only, and conservative — when unsure it KEEPS
/// the line. A transcript not in the "[hh:mm:ss] Me|Them: …" shape comes back
/// unchanged.
///
/// Ported from the C# original in Odin (Features/Meetings/TranscriptReconciler.cs);
/// behaviour is locked to that implementation by the golden cases in
/// HuginnCoreTests, which were generated by running it.
public enum TranscriptReconciler {

    private static let lineRegex: NSRegularExpression = {
        // Pattern is a literal, so it cannot fail to compile at runtime.
        try! NSRegularExpression(
            pattern: #"^\s*\[(\d{1,2}):(\d{2}):(\d{2})\]\s*(Me|Them)\s*:\s*(.*)$"#,
            options: [.caseInsensitive]
        )
    }()

    private static let shortLineWords = 4        // below this, the conservative single-line rule
    private static let contentWordLen = 5        // this long counts as "content", not filler
    private static let verbatimContainment = 0.90  // almost every word was theirs → echo, no further questions
    private static let contentContainment = 0.60   // else this share of its distinctive words must be theirs
    private static let noContentContainment = 0.85 // a line with no distinctive words needs a near-total match
    private static let fragmentContainment = 0.60  // short line whose words are theirs, and they spoke first

    /// - Parameters:
    ///   - windowSeconds: How far apart an echo and its original may be. This
    ///     is ASR chunk/timestamp drift, not acoustic delay: the two tracks
    ///     split the same speech at different points, so an echo can land ~15s
    ///     after the line it came from.
    ///   - containment: For a substantive (>=4-word) "Me" line, drop it if this
    ///     fraction of its distinct words appear anywhere in nearby "Them" speech.
    ///   - shortJaccard: For a short (<4-word) "Me" line, require a near-exact
    ///     match against a SINGLE "Them" line, so a genuine one-word question
    ///     is not discarded merely for sharing a word.
    public static func deEcho(
        _ transcript: String,
        windowSeconds: Double = 20.0,
        containment: Double = 0.70,
        shortJaccard: Double = 0.80
    ) -> DeEchoResult {
        guard !transcript.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            return DeEchoResult(text: transcript, removedEchoes: 0, meLines: 0, themLines: 0)
        }

        let lines = transcript.replacingOccurrences(of: "\r\n", with: "\n").components(separatedBy: "\n")

        var times = [Double?](repeating: nil, count: lines.count)
        var speakers = [String?](repeating: nil, count: lines.count)
        var tokens = [[String]](repeating: [], count: lines.count)
        var them: [(t: Double, tok: [String])] = []
        var meCount = 0
        var themCount = 0

        for (i, line) in lines.enumerated() {
            guard let parsed = parse(line) else { continue }
            times[i] = parsed.seconds
            speakers[i] = parsed.speaker
            tokens[i] = parsed.tokens
            if parsed.speaker == "Me" {
                meCount += 1
            } else {
                themCount += 1
                them.append((parsed.seconds, parsed.tokens))
            }
        }

        var remove = [Bool](repeating: false, count: lines.count)
        var removed = 0

        for i in 0..<lines.count {
            guard speakers[i] == "Me", let t = times[i], !tokens[i].isEmpty else { continue }
            let me = Set(tokens[i])

            // SHORT line: compare against ONE "Them" line at a time. A union
            // would swallow a genuine "AR?" the moment any nearby line happened
            // to contain that word.
            if me.count < shortLineWords {
                for entry in them {
                    let lag = t - entry.t                    // > 0 when they spoke first
                    if abs(lag) > windowSeconds { continue }
                    if shortIsEcho(me: me, themTokens: entry.tok, lag: lag, shortJaccard: shortJaccard) {
                        remove[i] = true
                        removed += 1
                        break
                    }
                }
                continue
            }

            // SUBSTANTIVE line: compare against the UNION of every "Them" line
            // in the window. The two tracks chunk the same speech differently —
            // one "Me" line can fuse two "Them" lines, or be half of one — so
            // matching a single line misses those.
            var nearby = Set<String>()
            for entry in them where abs(entry.t - t) <= windowSeconds {
                nearby.formUnion(entry.tok)
            }
            if !nearby.isEmpty, longIsEcho(me: me, nearbyThem: nearby, containment: containment) {
                remove[i] = true
                removed += 1
            }
        }

        guard removed > 0 else {
            return DeEchoResult(text: transcript, removedEchoes: 0, meLines: meCount, themLines: themCount)
        }

        var kept: [String] = []
        kept.reserveCapacity(lines.count)
        for (i, line) in lines.enumerated() where !remove[i] {
            kept.append(line)
        }
        // Matches the C# `TrimEnd() + "\n"`: exactly one trailing newline.
        var trimmed = kept.joined(separator: "\n")
        while let last = trimmed.last, last.isWhitespace {
            trimmed.removeLast()
        }

        return DeEchoResult(
            text: trimmed + "\n",
            removedEchoes: removed,
            meLines: meCount,
            themLines: themCount
        )
    }

    // MARK: - rules

    /// Short line vs ONE "Them" line. `lag` is (me − them) in seconds, positive
    /// when they spoke first.
    private static func shortIsEcho(
        me: Set<String>,
        themTokens: [String],
        lag: Double,
        shortJaccard: Double
    ) -> Bool {
        let them = Set(themTokens)
        guard !them.isEmpty else { return false }
        let inter = me.filter { them.contains($0) }.count

        // (a) Echoed backchannel — the two lines are near-identical
        //     ("Okay." <-> "Okay."). Direction-agnostic, since both tracks chunk
        //     a one-word utterance at essentially the same instant.
        let union = me.count + them.count - inter
        if union > 0, Double(inter) / Double(union) >= shortJaccard { return true }

        // (b) FRAGMENT echo — the mic re-chunks their sentence into pieces, so a
        //     few of their words stand alone as a "Me" line. A fragment is a
        //     SUBSET, never a near-equal, so (a) cannot see it. Gate on
        //     THEY-SPOKE-FIRST: an echo cannot precede its source. That single
        //     condition is what keeps a genuine short question alive.
        return lag >= 0 && Double(inter) / Double(me.count) >= fragmentContainment
    }

    /// Substantive line vs the UNION of nearby "Them" speech.
    ///  - Gate 1 (containment): most of the line's words were said by them nearby.
    ///  - Near-verbatim bypass: if almost EVERY word came from them it is their
    ///    sentence, full stop. This matters because the mic transcribes the echo
    ///    imperfectly and the words it mangles are precisely the distinctive
    ///    ones, which would fail gate 2.
    ///  - Gate 2 (content containment): for the middle band, require its
    ///    distinctive (long) words to be theirs too, so a genuine interjection
    ///    built from common words is not swallowed by a large union.
    private static func longIsEcho(
        me: Set<String>,
        nearbyThem: Set<String>,
        containment: Double
    ) -> Bool {
        let inter = me.filter { nearbyThem.contains($0) }.count
        let overall = Double(inter) / Double(me.count)
        if overall < containment { return false }
        if overall >= verbatimContainment { return true }

        var contentTotal = 0
        var contentHit = 0
        for word in me where word.count >= contentWordLen {
            contentTotal += 1
            if nearbyThem.contains(word) { contentHit += 1 }
        }
        if contentTotal == 0 { return overall >= noContentContainment }
        return Double(contentHit) / Double(contentTotal) >= contentContainment
    }

    // MARK: - parsing

    private static func parse(_ line: String) -> (seconds: Double, speaker: String, tokens: [String])? {
        let ns = line as NSString
        let full = NSRange(location: 0, length: ns.length)
        guard let m = lineRegex.firstMatch(in: line, options: [], range: full) else { return nil }

        let h = Int(ns.substring(with: m.range(at: 1))) ?? 0
        let mm = Int(ns.substring(with: m.range(at: 2))) ?? 0
        let ss = Int(ns.substring(with: m.range(at: 3))) ?? 0
        let rawSpeaker = ns.substring(with: m.range(at: 4))
        let speaker = rawSpeaker.lowercased() == "me" ? "Me" : "Them"

        return (
            Double(h * 3600 + mm * 60 + ss),
            speaker,
            tokenize(ns.substring(with: m.range(at: 5)))
        )
    }

    /// Lowercase word list, punctuation stripped. Single characters are dropped:
    /// "it's" splits to "it" + "s", and those stray fragments only add noise to
    /// the overlap counts.
    static func tokenize(_ s: String) -> [String] {
        var current = ""
        var out: [String] = []
        for ch in s.lowercased() {
            if ch.isLetter || ch.isNumber {
                current.append(ch)
            } else if !current.isEmpty {
                if current.count > 1 { out.append(current) }
                current = ""
            }
        }
        if current.count > 1 { out.append(current) }
        return out
    }
}
